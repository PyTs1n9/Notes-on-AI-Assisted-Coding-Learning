# ============ 第十三课演示：给真实的单车租赁数据做一次"数据审计" ============
import pandas as pd                                    # 读表、造审计表

df = pd.read_csv('day.csv', encoding='utf-8-sig')      # 真实 UCI 共享单车数据：2011-2012 两年共 731 天

# ---------- 第 1 步：先看"多大、每列叫什么、什么类型" ----------
print(df.shape)                                        # 函数①：行数 × 列数 → (731, 16)
print(df.dtypes)                                       # 函数②：索引 = 字段名，值 = 字段类型

# ---------- 第 2 步：看前 5 行，认识数据长什么样 ----------
print(df.head())                                       # 函数③：前 5 行快照

# ---------- 第 3 步：逐列数缺失值（空格子） ----------
print(df.isnull().sum())                               # 函数④：每列各缺几个；全 0 = 这份数据没有缺失

# ---------- 第 4 步：数值列统计摘要 ----------
print(df.describe().round(2))                          # 函数⑤：count/mean/std/min/四分位/max

# ---------- 第 5 步：审计表雏形：每个字段一行体检结果 ----------
audit = pd.DataFrame({                                 # 函数⑥：两个 Series 字段名相同，自动按字段对齐
    '类型': df.dtypes,                                 # 第 1 列：字段类型
    '缺失数': df.isnull().sum(),                       # 第 2 列：该字段缺失几个
})
print(audit)                                           # 索引 = 字段名，16 个字段一屏看完
